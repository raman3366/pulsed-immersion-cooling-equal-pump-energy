@dataclass
class HeatModel:
    kind: str                     # poly | table | const | none
    coeffs: list | None = None    # value polynomial in the mapped variable
    table: list | None = None     # [(x, q)]
    scale: float = 1.0            # mapped variable = scale * (t - t_pre)
    const_w: float = 0.0
    label: str = ""
    t_dis: float = 0.0

    def power(self, tau):
        """Per-cell power [W] at discharge time tau = t - t_pre (array)."""
        tau = np.asarray(tau, float)
        x = self.scale * tau
        if self.kind == "poly":
            p = poly(self.coeffs, x)
        elif self.kind == "table":
            tx, tq = np.array(self.table).T
            p = np.interp(x, tx, tq)
        elif self.kind == "const":
            p = np.full_like(tau, self.const_w)
        else:
            p = np.zeros_like(tau)
        return p


def heat_model(cfg):
    """The heat model of a case, its power multiplied by HEAT_SCALE (D-A.3,
    NEW-6; 1 for every confirmatory run)."""
    hm = _heat_model_unscaled(cfg)
    k = float(getattr(cfg, "heat_scale", 1.0))
    if k == 1.0 or hm.kind == "none":
        return hm
    if hm.kind == "poly":
        hm.coeffs = [k * float(c) for c in hm.coeffs]
    elif hm.kind == "table":
        hm.table = [(float(x), k * float(q)) for x, q in hm.table]
    else:
        hm.const_w = k * float(hm.const_w)
    hm.label = f"{hm.label} x {k:.17g} (HEAT_SCALE)"
    return hm


def _heat_model_unscaled(cfg):
    if cfg.heat_model == "none":
        return HeatModel("none", label="none (isothermal)", t_dis=cfg.t_dis)
    if cfg.heat_model == "const":
        return HeatModel("const", const_w=float(cfg.heat_w),
                         label=f"constant {cfg.heat_w:g} W/cell",
                         t_dis=cfg.t_dis)
    if cfg.heat_model == "H1":
        h1 = _yaml("data/reference/heatgen_h1.yaml")["liu3c_h1"]["table"]
        return HeatModel("table", table=list(zip(map(float, h1["t_s"]),
                                                 map(float, h1["q_W"]))),
                         label="H1 3C Bernardi table (heatgen_h1.yaml)",
                         t_dis=cfg.t_dis)
    # H0
    if cfg.crate == 3:
        hg = _yaml("data/reference/heatgen.yaml")["liu3c"]
        c = list(map(float, hg["coefficients"]))
        if cfg.h0_time == "seconds":
            return HeatModel("poly", coeffs=c, scale=1.0,
                             label="H0 3C Liu Eq. 5, t in s (heatgen.yaml)",
                             t_dis=cfg.t_dis)
        tref = float(_yaml("data/reference/heatgen_h0_fig3b.yaml")
                     ["liu3c_fig3b_vs_eq5"]["T_ref_s"])
        return HeatModel("poly", coeffs=c, scale=tref / discharge_time(3),
                         label=f"H0 3C Liu Eq. 5 DOD-normalised "
                               f"(t x {tref:g}/900 s)", t_dis=cfg.t_dis)
    h0 = _yaml("data/reference/heatgen_h0_fig3b.yaml")[f"liu{cfg.crate}c_fig3b"]
    return HeatModel("poly", coeffs=list(map(float, h0["coefficients_z"])),
                     scale=1.0 / discharge_time(cfg.crate),
                     label=f"H0 {cfg.crate}C digitised Fig 3b, z = t/t_dis",
                     t_dis=cfg.t_dis)


def heat_window(cfg):
    """(timeStart, duration) of the source: active for every step whose
    end time lies in (t_pre, t_pre + t_dis] (sources are evaluated at the
    new time level; half-step margins absorb the time round-off)."""
    return cfg.t_pre + 0.5 * cfg.dt, cfg.t_dis


def injected_power(cfg, hm, t):
    """Per-cell power the solver injects in the step ending at t."""
    t = np.asarray(t, float)
    t0, dur = heat_window(cfg)
    on = (t >= t0) & (t <= t0 + dur)
    return np.where(on, hm.power(t - cfg.t_pre), 0.0)


