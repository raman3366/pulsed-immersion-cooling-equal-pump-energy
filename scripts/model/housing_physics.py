def _f17(x):
    return f"{float(x):.17g}"


def _poly_entry(coeffs):
    """OpenFOAM Polynomial Function1 '((c0 0) (c1 1) ...)' at 17 digits."""
    return "(" + " ".join(f"({_f17(c)} {k})" for k, c in enumerate(coeffs)) + ")"


