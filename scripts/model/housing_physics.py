def tilt_vector(seed):
    """Random unit direction of member `seed` (numpy default_rng; seed 0 =
    no tilt)."""
    if seed == 0:
        return None
    v = np.random.default_rng(int(seed)).normal(size=3)
    return v / np.linalg.norm(v)


TILT_REGIONS = [r for r in REGIONS if r != "fluid"]


def tilt_setup(cfg):
    """Tilt T += TILT_K * (n.(x - c)) / L, a smooth linear field in a random
    direction n (D-L seed), applied to the six CELLS at heat-on. c is the
    module centre (0, 0, 32.5 mm) and L the largest |n.(x - c)| over the
    module box (x +-30, y +-23, z 0..72 mm), so the tilt stays within
    +-TILT_K in every cell. Cells only, by design: (i) the module is
    symmetric about c, so the added enthalpy is zero to round-off and the
    ledger is untouched; (ii) the fluid keeps its pre-circulated state, so
    the D-F maximum-principle bound T_fluid >= T_in - 0.05 K is not spent on
    the seed; (iii) the asymmetric cell heating perturbs the buoyant flow
    from the first heated step."""
    n = tilt_vector(cfg.seed)
    if n is None:
        return None
    c = np.array([0.0, 0.0, 0.0325])
    corners = np.array([[x, y, z] for x in (-0.030, 0.030)
                        for y in (-0.023, 0.023) for z in (0.0, 0.072)])
    L = float(np.max(np.abs((corners - c) @ n)))
    return dict(n=n.tolist(), c=c.tolist(), L=L, amp=cfg.tilt_k)


# OpenFOAM ascii field I/O (the tilt edits T in place: setExprFields v2606
# aborts on any expression that reads an existing field of these regions,
# "Attempted non-const reference to const object", 2026-09-25 smoke)
def _internal_span(txt):
    import re
    m = re.search(r"^internalField\s+", txt, re.M)
    if not m:
        raise ValueError("no internalField")
    end = txt.index("boundaryField", m.end())
    semi = txt.rindex(";", m.end(), end)
    return m.start(), semi + 1


def read_internal(path, ncmpt=1):
    """internalField of an ascii OpenFOAM field file (uniform or
    nonuniform List<scalar|vector>) as an (n,) or (n, 3) array; uniform
    returns a 1-element array."""
    import re
    txt = Path(path).read_text()
    a, b = _internal_span(txt)
    body = txt[a:b]
    mu = re.match(r"internalField\s+uniform\s+(.*);\s*$", body, re.S)
    if mu:
        v = np.array(mu.group(1).strip().strip("()").split(), dtype=float)
        if v.size != ncmpt:
            raise ValueError(f"{path}: uniform value has {v.size} components")
        return v if ncmpt == 1 else v.reshape(1, ncmpt)
    mn = re.match(r"internalField\s+nonuniform\s+List<\w+>\s*(\d+)\s*\((.*)\)"
                  r"\s*;\s*$", body, re.S)
    if not mn:
        raise ValueError(f"{path}: cannot parse internalField")
    n = int(mn.group(1))
    vals = np.array(mn.group(2).replace("(", " ").replace(")", " ").split(),
                    dtype=float)
    if vals.size != n * ncmpt:
        raise ValueError(f"{path}: {vals.size} values for {n} x {ncmpt}")
    return vals.reshape(n, ncmpt) if ncmpt > 1 else vals


def write_internal_scalar(path, values):
    """Replace the internalField of an ascii scalar field file by a
    nonuniform list at 17 significant digits (exact round-trip)."""
    path = Path(path)
    txt = path.read_text()
    a, b = _internal_span(txt)
    vals = "\n".join(f"{v:.17g}" for v in np.asarray(values, float))
    new = (f"internalField   nonuniform List<scalar> \n{len(values)}\n(\n"
           f"{vals}\n)\n;")
    path.write_text(txt[:a] + new + txt[b:])


def tilt_field(T, C, ts):
    """T + amp * (n.(C - c)) / L (T scalar or (n,), C (n, 3))."""
    n, c = np.asarray(ts["n"]), np.asarray(ts["c"])
    return T + ts["amp"] * ((C - c) @ n) / ts["L"]


def apply_tilt(case, time_name, cfg):
    """Tilt T of every cell region at time_name (needs C and V written there by
    postProcess -funcs '(writeCellCentres writeCellVolumes)'). Returns the
    per-region record, including the enthalpy the tilt adds
    (sum rho c_p dT V; ~0 for a centred linear tilt), and removes C, Cx, Cy,
    Cz, V again so the restart directory holds only solver fields."""
    ts = tilt_setup(cfg)
    case = Path(case)
    cell = _yaml("data/reference/properties.yaml")["cell"]
    co, _ = fluid_coeffs(cfg)
    rec = dict(seed=cfg.seed, tilt=ts, time=time_name, regions={})
    for r in TILT_REGIONS:
        d = case / time_name / r
        C = read_internal(d / "C", 3)
        V = read_internal(d / "V")
        T = read_internal(d / "T")
        if T.size == 1:
            T = np.full(C.shape[0], float(T[0]))
        if not (T.size == C.shape[0] == V.size):
            raise ValueError(f"{d}: T/C/V sizes differ")
        Tn = tilt_field(T, C, ts)
        dT = Tn - T
        if r == "fluid":
            rc = poly(co["rho"], T) * poly(co["cp"], T)
        else:
            rc = float(cell["density"]) * float(cell["specific_heat"])
        write_internal_scalar(d / "T", Tn)
        for f in ("C", "Cx", "Cy", "Cz", "V"):
            (d / f).unlink(missing_ok=True)
        rec["regions"][r] = dict(n=int(T.size), dT_min=float(dT.min()),
                                 dT_max=float(dT.max()),
                                 dH_J=float(np.sum(rc * dT * V)))
    rec["dH_total_J"] = sum(v["dH_J"] for v in rec["regions"].values())
    (case / "tilt.json").write_text(json.dumps(rec, indent=1) + "\n")
    return rec


