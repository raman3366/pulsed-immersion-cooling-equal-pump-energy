def time_dirs(case):
    """[(name, value)] of the numeric time directories of a (serial or
    reconstructed) case, sorted by value; 0.orig and the like excluded."""
    out = []
    for d in Path(case).iterdir():
        if not d.is_dir():
            continue
        try:
            v = float(d.name)
        except ValueError:
            continue
        out.append((d.name, v))
    return sorted(out, key=lambda x: x[1])


