OUTLET_P_VALUE = 0.0         # D-G.1: the static pressure p on the outlet face (gauge)


def outlet_p_rgh(cfg):
    """The riser-top outlet's p_rgh boundary condition (system/fluid/
    changeDictionaryDict; the housing has no constant/fluid/hRef, so
    ghRef = 0 and gh = g & C):
    - OUTLET_P prgh [P] (D-G as built, §4.3): fixedValue p_rgh = 0, so the
      face's static pressure p = p_rgh + rho gh follows the local density;
    - OUTLET_P p (D-G.1 diagnostic): prghPressure with p = 0 on the face
      (v2606 prghPressureFvPatchScalarField: p_rgh = p - rho (g & Cf -
      ghRef); syntax of the tutorial heatTransfer/buoyantSimpleFoam/
      comfortHotRoom, 0.orig/p_rgh). Its value entry is the start-up p_rgh
      at the face, p - rho0 g.r_out = rho0 |g| z_out with rho0 = rho(T_in)
      (the uniform initial T is T_in), which scripts/hydrostatic_init.py
      recomputes from p and z_out for the hydrostatic initial state.
    Returns the patch entry text (one line, OpenFOAM braces)."""
    if cfg.outlet_p == "prgh":
        return "{ type fixedValue; value uniform 0; }"
    z_out = port_meta(cfg)["z_outlet_m"]
    gh_out = G_VEC[2] * z_out                   # g & C at the face (g along -z)
    v = OUTLET_P_VALUE - rho_inlet(cfg) * gh_out
    return (f"{{ type prghPressure; p uniform {_f17(OUTLET_P_VALUE)}; "
            f"value uniform {_f17(v)}; }}   // D-G.1 diagnostic (OUTLET_P=p): "
            "p = 0 on the face")


def courant_limited_dt(level, q_peak_ml_min, dt_star=DT_STAR_PROV_MS * 1e-3,
                       port_mult=1):
    """NEW-19 high-flow checks (decided 2026-09-25): the largest ladder dt
    <= dt_star at which the developed-laminar PEAK outflow Courant number of
    the riser column stays <= 1 at the peak flow (k0_blockmesh housing
    report; the peak factor 1.7355 of the 10 x 46 mm section is a floor, so
    the solver's bulk Co gate, D-F.1, still binds). 6.25 ms on medium at
    500 mL/min, 3.125 ms on medium at 1000, 1.5625 / 0.78125 ms on fine /
    xfine at 2000 (the same for dt* = 12.5 or 6.25 ms). Returns (dt, dt_max)."""
    import k0_targets as KT
    topo = KB.Topology(KB.load_geometry(), KB.DESIGN_HOUSING, "housing",
                       port_mult)
    oc = KB.housing_report(topo, level)["outflow_column"]
    dt_max = oc["dt_max_peak_s"] * (KT.CO_OUTFLOW_Q_M3S * 6e7) / q_peak_ml_min
    dt = dt_star
    while dt > dt_max * (1 + 1e-12):
        dt /= 2
    return dt, dt_max


