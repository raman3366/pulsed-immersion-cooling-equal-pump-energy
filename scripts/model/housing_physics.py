@dataclass
class Config:
    waveform: str = "steady"
    qbar_ml_min: float = 90.0
    freq_hz: float = 0.0
    amp: float = 0.0
    duty: float = 0.0
    edge: str = "dt"
    dt: float = 0.0125                   # provisional dt* (NEW-2.1)
    n_min: int = 40
    n_phi_min: int = 8
    diagnostic: bool = False
    fluid_props: str = "tdep"
    beta: float | None = None
    coolant_k: float | None = None
    heat_model: str = "H0"
    crate: int = 3
    heat_w: float | None = None
    heat_scale: float = 1.0              # D-A.3 / NEW-6: power multiplier (robustness)
    h0_time: str = "seconds"
    heat_diagnostic: bool = False
    precirc_s: float | None = None       # None = auto (NEW-14)
    precirc_check: str = "strict"        # NEW-14.1 (c) / NEW-14.2: report = not claim-eligible
    run_stage: str = "full"
    heat_steps: int | None = None
    seed: int = 0
    tilt_k: float = 0.05
    scheme: str = "cand1"
    nouter: int = 2
    samplers: bool = True
    sampler_periods: int = 10
    write_s: float = 30.0
    measure_s: float | None = None
    grid: str = "coarse"
    port_mult: int = 1
    zlever: str = "far"
    outlet_p: str = "prgh"               # D-G.1: 'p' = the outlet on p (diagnostic)
    div_u: str = "scheme"                # D-P.9: 'linear' = Gauss linear div(phi,U) (diagnostic)
    phi_face: bool = False               # D-P.9: the face-based Phi monitor (instrument)
    init_from: str = ""
    family_block: str = ""
    claim_note: list = field(default_factory=list)

    # ---- construction ---------------------------------------------------
    @classmethod
    def from_env(cls, env=None):
        """Read the switches from the environment (case.env via
        Allrun.pre). Unknown values are hard failures."""
        e = dict(os.environ if env is None else env)

        def fnum(k, d):
            v = e.get(k, "")
            return float(v) if v != "" else d

        c = cls()
        c.waveform = e.get("WAVEFORM", "steady")
        c.qbar_ml_min = fnum("QBAR_ML_MIN", 90.0)
        if c.waveform == "steady":
            c.freq_hz, c.amp, c.duty = 0.0, 0.0, 0.0
        else:
            c.freq_hz = fnum("FREQ_HZ", 1.0)
            c.amp = fnum("AMP", 0.6) if c.waveform == "sine" else 0.0
            c.duty = fnum("DUTY", 0.25) if c.waveform == "square" else 0.0
        c.edge = e.get("EDGE", "dt")
        c.dt = fnum("DT_MS", DT_STAR_PROV_MS) * 1e-3
        c.n_min = int(fnum("N_MIN", 40))
        c.n_phi_min = int(fnum("N_PHI_MIN", 8))
        c.diagnostic = e.get("DIAGNOSTIC", "0") == "1"
        c.fluid_props = e.get("FLUID_PROPS", "tdep")
        c.beta = fnum("BETA", None) if e.get("BETA") else None
        c.coolant_k = fnum("COOLANT_K", None) if e.get("COOLANT_K") else None
        c.heat_model = e.get("HEAT_MODEL", "H0")
        c.crate = int(fnum("CRATE", 3))
        c.heat_w = fnum("HEAT_W", None) if e.get("HEAT_W") else None
        c.heat_scale = fnum("HEAT_SCALE", 1.0)
        c.h0_time = e.get("H0_TIME", "seconds")
        c.heat_diagnostic = e.get("HEAT_DIAGNOSTIC", "0") == "1"
        p = e.get("PRECIRC_S", "auto")
        c.precirc_s = None if p in ("", "auto") else float(p)
        c.run_stage = e.get("RUN_STAGE", "full")
        c.precirc_check = e.get("PRECIRC_CHECK", "") or "strict"
        c.heat_steps = int(e["HEAT_STEPS"]) if e.get("HEAT_STEPS") else None
        c.seed = int(fnum("SEED", 0))
        c.tilt_k = fnum("TILT_K", 0.05)
        c.scheme = e.get("SCHEME", "cand1")
        c.nouter = int(fnum("NOUTER", 2))
        c.samplers = e.get("SAMPLERS", "1") != "0"
        c.sampler_periods = int(fnum("SAMPLER_PERIODS", 10))
        c.write_s = fnum("WRITE_S", 30.0)
        c.measure_s = fnum("MEASURE_S", None) if e.get("MEASURE_S") else None
        c.grid = e.get("GRID", "coarse")
        c.port_mult = int(fnum("PORT_MULT", 1))
        c.zlever = e.get("K0_ZLEVER", "") or "far"
        c.outlet_p = e.get("OUTLET_P", "") or "prgh"
        c.div_u = e.get("DIV_U", "") or "scheme"
        pf = e.get("PHI_FACE", "") or "0"
        if pf not in ("0", "1"):
            raise ConfigError(f"housing_physics: PHI_FACE {pf!r} (0 or 1)")
        c.phi_face = pf == "1"
        c.init_from = e.get("INIT_FROM", "")
        c.family_block = e.get("FAMILY_BLOCK", "")
        c.validate()
        return c

    def validate(self):
        bad = []
        if self.waveform not in ("steady", "sine", "square"):
            bad.append(f"WAVEFORM {self.waveform!r}")
        if self.waveform != "steady" and not self.freq_hz > 0:
            bad.append("FREQ_HZ must be > 0 for a pulsed waveform")
        if self.waveform == "sine" and not 0 < self.amp <= 1:
            bad.append(f"AMP {self.amp}: 0 < A <= 1 (reversing flow is "
                       "companion scope)")
        if self.waveform == "square" and not 0 < self.duty < 1:
            bad.append(f"DUTY {self.duty}: 0 < D < 1")
        if self.qbar_ml_min < 0:
            bad.append("QBAR_ML_MIN < 0")
        if self.fluid_props not in PROPS_SETS:
            bad.append(f"FLUID_PROPS {self.fluid_props!r} not in {PROPS_SETS}")
        if (self.beta is not None or self.coolant_k is not None) \
                and self.fluid_props != "const":
            bad.append("BETA / COOLANT_K overrides act on the constant set "
                       "only (FLUID_PROPS=const); tdep takes beta and k "
                       "from the fitted polynomials")
        if self.heat_model not in HEAT_MODELS:
            bad.append(f"HEAT_MODEL {self.heat_model!r} not in {HEAT_MODELS}")
        if self.crate not in (1, 2, 3):
            bad.append(f"CRATE {self.crate}")
        if self.heat_model == "const" and not (self.heat_w and self.heat_w > 0):
            bad.append("HEAT_MODEL const needs HEAT_W > 0 [W per cell]")
        if not (math.isfinite(self.heat_scale) and self.heat_scale > 0):
            bad.append(f"HEAT_SCALE {self.heat_scale}: must be > 0")
        if self.heat_scale != 1.0 and self.heat_model == "none":
            bad.append("HEAT_SCALE needs a heat source (HEAT_MODEL none)")
        if self.h0_time not in ("seconds", "dod"):
            bad.append(f"H0_TIME {self.h0_time!r}")
        if self.run_stage not in RUN_STAGES:
            bad.append(f"RUN_STAGE {self.run_stage!r} not in {RUN_STAGES}")
        if self.precirc_check not in ("strict", "report"):
            bad.append(f"PRECIRC_CHECK {self.precirc_check!r} not in (strict, report)")
        if self.scheme not in SCHEMES:
            bad.append(f"SCHEME {self.scheme!r} not in {SCHEMES}")
        if self.seed < 0:
            bad.append("SEED < 0")
        if self.seed and self.run_stage == "full":
            bad.append("SEED > 0 needs the two-stage run (RUN_STAGE precirc "
                       "then Allrun.heat, or heat with INIT_FROM): the tilt "
                       "is applied to the written pre-circulated state at "
                       "heat-on")
        if self.run_stage == "heat" and self.precirc_s == 0:
            bad.append("RUN_STAGE=heat needs a pre-circulation (PRECIRC_S > 0)")
        if self.heat_steps is not None and self.heat_steps < 1:
            bad.append("HEAT_STEPS < 1")
        if self.measure_s is not None and self.heat_model != "none":
            bad.append("MEASURE_S sets the window of an isothermal run "
                       "(HEAT_MODEL none); a discharge lasts t_discharge")
        if self.port_mult not in (1, 2, 4):
            bad.append(f"PORT_MULT {self.port_mult}")
        if self.zlever not in ZLEVERS:
            bad.append(f"K0_ZLEVER {self.zlever!r} not in {ZLEVERS}")
        if self.outlet_p not in OUTLET_P_MODES:
            bad.append(f"OUTLET_P {self.outlet_p!r} not in {OUTLET_P_MODES}")
        if self.div_u not in DIV_U_MODES:
            bad.append(f"DIV_U {self.div_u!r} not in {DIV_U_MODES}")
        if self.edge not in ("dt", "ideal"):
            try:
                v = float(self.edge)
                if not v > 0:
                    raise ValueError
            except ValueError:
                bad.append(f"EDGE {self.edge!r}: dt, ideal or a time in ms")
        if bad:
            raise ConfigError("housing_physics: " + "; ".join(bad))
        # H1 enforcement (docs/pending-decisions/WP2.7.md item 2)
        if self.heat_model == "H1":
            h1 = _yaml("data/reference/heatgen_h1.yaml")
            if self.crate != 3:
                raise ConfigError("housing_physics: H1 exists at 3C only "
                                  "(heatgen_h1.yaml)")
            if not h1.get("usable_as_Hstar", False):
                if not self.heat_diagnostic:
                    raise ConfigError(
                        "housing_physics: H1 refused - heatgen_h1.yaml says "
                        "usable_as_Hstar: false (" +
                        str(h1.get("usable_as_Hstar_reason", ""))[:160] +
                        "...). HEAT_DIAGNOSTIC=1 runs it as a never "
                        "claim-eligible diagnostic.")
                self.claim_note.append("H1 used as a diagnostic while its "
                                       "energy gate fails (usable_as_Hstar "
                                       "false)")
        return self

    # ---- time lattice ----------------------------------------------------
    @property
    def period(self):
        return None if self.waveform == "steady" else 1.0 / self.freq_hz

    def steps(self, duration, what):
        n, ok = G._steps(duration, self.dt)
        if not ok:
            raise ConfigError(f"housing_physics: {what} {duration:.10g} s = "
                              f"{duration / self.dt:.10g} steps of dt "
                              f"{self.dt:g} s (not an integer; D-T lattice)")
        return n

    @property
    def ramp_s(self):
        """Start-up ramp of the inlet waveform (template §4.4 rule)."""
        return 2.0 if self.period is None else max(2.0, self.period)

    @property
    def t_dis(self):
        """Duration of the stage after t_pre [s]: the discharge, or for an
        isothermal run (HEAT_MODEL none) the measurement window MEASURE_S
        (default 10 periods, steady 30 s)."""
        if self.heat_steps is not None:
            return self.heat_steps * self.dt
        if self.heat_model == "none":
            if self.measure_s is not None:
                return self.measure_s
            return 30.0 if self.period is None else 10 * self.period
        return discharge_time(self.crate)

    @property
    def t_pre(self):
        """Pre-circulation duration [s] (NEW-14.1, PROJECT.md §2.5,
        2026-09-28): auto = PRECIRC_MIN_S (120 s) when steady; pulsed = the
        smallest whole number of periods >= max(120 s, ramp + 5 periods).
        The 30 s of the 2026-09-24 rule could not pass the stationarity
        check (3 windows of 10 s, 4 needed), and GDT1's port-flow kinetic
        energy still rose 4.7 % per 10 s at 30 s."""
        if self.precirc_s is not None:
            return self.precirc_s
        if self.period is None:
            return PRECIRC_MIN_S
        P = self.period
        need = max(PRECIRC_MIN_S, self.ramp_s + PRECIRC_PERIODS * P)
        return math.ceil(need / P - 1e-9) * P

    @property
    def t_end(self):
        return self.t_pre if self.run_stage == "precirc" else \
            self.t_pre + self.t_dis

    def valve_edge(self):
        """Square-wave valve edge [s] or None (steady, sine, ideal)."""
        if self.waveform != "square" or self.edge == "ideal":
            return None
        if self.edge == "dt":
            return G.valve_edge_required(self.duty * self.period)
        return float(self.edge) * 1e-3

    def lattice(self):
        """Integer step counts of every timing quantity; hard failure
        (ConfigError) unless gates.lattice_gate passes (D-T, NEW-2)."""
        k = math.log2(DT_BASE / self.dt)
        if abs(k - round(k)) > 1e-9 or round(k) < 0:
            raise ConfigError(f"housing_physics: dt {self.dt * 1e3:g} ms is "
                              "not 25*2^-k ms (D-T ladder)")
        P = self.period
        on = self.duty * P if self.waveform == "square" else None
        tau = self.valve_edge()
        edge_sens = self.waveform == "square" and self.edge != "dt"
        if P is None:
            n_per = None
            m_phase = self.steps(STEADY_SAMPLE_S, "steady monitor interval")
            n_nom = self.steps(STEADY_PERIOD_S, "steady sampler period")
            n_phi = G.phase_samplers(n_nom)
            s_samp = n_nom // n_phi
        else:
            n_per = self.steps(P, "period")
            n_phi = G.phase_samplers(n_per)
            m_phase = n_per // n_phi
            s_samp = m_phase
        # monitors: the phase cadence itself when it is <= 100 ms, else its
        # largest divisor <= 50 ms - phase-locked either way (they divide the
        # phase cadence) and fine enough for the ledger integrals
        if m_phase * self.dt <= 2 * STEADY_SAMPLE_S + 1e-12:
            m_mon = m_phase
        else:
            cap = max(1, int(round(STEADY_SAMPLE_S / self.dt)))
            m_mon = max(d for d in _divisors(m_phase) if d <= cap)
        # hydraulic-budget monitors (KE, Phi, W_b and the gradU / expression
        # fields behind them): every step on square waves, whose valve
        # edges last a few steps (review of WP 2.5c, SHOULD-FIX 4: at M
        # steps a trapezoid across a 4-step edge errs by several percent),
        # the monitor cadence otherwise
        m_hyd = 1 if self.waveform == "square" else m_mon
        # Courant monitors (D-F.9 (4)): every step on square waves, whose
        # every-step maximum sits at the field steps a phase-locked cadence
        # never samples (the end of the opening ramp and the two steps
        # after it); the monitor cadence otherwise
        m_co = 1 if self.waveform == "square" else m_mon
        ok, detail = G.lattice_gate(
            self.dt, period=P, on_time=on, sample=s_samp * self.dt,
            valve_edge=tau, n_min=self.n_min,
            n_phase_min=self.n_phi_min if P is not None else 8,
            diagnostic=self.diagnostic, edge_sensitivity=edge_sens)
        if not ok:
            raise ConfigError(f"housing_physics: {detail}")
        tau_steps = None
        if tau is not None:
            tau_steps = self.steps(tau, "valve edge")
            if tau_steps % 2:
                raise ConfigError(
                    f"housing_physics: valve edge {tau_steps} steps is odd; "
                    "the edges are centred on the switching instants "
                    "(qs_model.Square), so tau_v/2 must be an integer step "
                    "count")
        if self.edge == "ideal" and self.waveform == "square":
            self.steps(on, "ON time")
        n_pre = self.steps(self.t_pre, "pre-circulation")
        if P is not None and n_pre % n_per:
            raise ConfigError(f"housing_physics: pre-circulation {self.t_pre:g}"
                              f" s is not a whole number of periods (heat-on "
                              "must be at waveform phase 0, NEW-14)")
        if n_pre % m_phase:
            raise ConfigError("housing_physics: pre-circulation is not a "
                              "multiple of the monitor cadence")
        n_dis = self.steps(self.t_dis, "discharge")
        if n_dis % m_mon:
            raise ConfigError(f"housing_physics: the discharge ({n_dis} steps) "
                              f"is not a multiple of the monitor cadence "
                              f"({m_mon} steps): the ledger needs a sample at "
                              "t_end")
        n_end = n_pre if self.run_stage == "precirc" else n_pre + n_dis
        # field writes: largest divisor of gcd(N_pre, N_end) (both writes
        # are restart points) not above the nominal WRITE_S
        base = math.gcd(n_pre, n_end) if n_pre else n_end
        cap_w = max(1, int(self.write_s / self.dt + 1e-9))
        w = max(d for d in _divisors(base) if d <= cap_w)
        # samplers: the last SAMPLER_PERIODS whole periods (nominal 1 s
        # for steady) before t_end, never before 0
        p_samp = P if P is not None else STEADY_PERIOD_S
        n_samp_per = self.steps(p_samp, "sampler period")
        k = min(self.sampler_periods, n_end // n_samp_per)
        t_samp0 = (n_end - k * n_samp_per) * self.dt
        if k == 0:              # shorter than one sampler period (smokes):
            t_samp0 = n_pre * self.dt       # sample the whole heated stage
        return dict(
            dt=self.dt, steps_per_period=n_per, n_phi=n_phi,
            monitor_steps=m_mon, hydraulic_steps=m_hyd, courant_steps=m_co,
            phase_steps=m_phase,
            sampler_steps=s_samp,
            valve_edge_s=tau, valve_edge_steps=tau_steps,
            on_steps=(self.steps(on, "ON time") if on else None),
            n_pre=n_pre, n_dis=n_dis, n_end=n_end, write_steps=w,
            sampler_periods=k, sampler_t0=t_samp0,
            time_precision=max(8, G.min_time_precision(max(self.t_end, 1.0),
                                                        self.dt)),
            lattice_detail=detail)

    # ---- flags -------------------------------------------------------------
    def claim_eligible(self):
        notes = list(self.claim_note)
        if self.heat_steps is not None:
            notes.append("smoke (HEAT_STEPS)")
        if self.diagnostic:
            notes.append("diagnostic lattice (ladder/coupling)")
        if self.waveform == "square" and self.edge != "dt":
            notes.append("valve-edge sensitivity")
        if self.heat_diagnostic:
            notes.append("HEAT_DIAGNOSTIC")
        if self.zlever != "far":
            notes.append("K0_ZLEVER=module (mesh option pending its D-row, "
                         "K0-design §10.14)")
        if self.outlet_p != "prgh":
            notes.append("OUTLET_P=p (outlet pressure on p: the D-G.1 "
                         "diagnostic BC, not the D-G as-built outlet)")
        if self.div_u != "scheme":
            notes.append("DIV_U=linear (Gauss linear div(phi,U): the D-P.9 "
                         "closure diagnostic, not a D-J scheme candidate)")
        # NEW-14.2: a claim-bearing run starts from a pre-circulated state
        # that passed the strict stationarity gate (housing_metrics applies
        # it); report mode is for smokes and diagnostic protocols, and an
        # impulsive start of a flowing case is a sensitivity (NEW-14)
        if self.precirc_check != "strict":
            notes.append("PRECIRC_CHECK=report (stationarity reported, not gated)")
        if self.precirc_s == 0 and self.qbar_ml_min > 0:
            notes.append("impulsive start (PRECIRC_S=0): sensitivity (NEW-14)")
        return (not notes), notes


def _divisors(n):
    out = set()
    for d in range(1, int(math.isqrt(n)) + 1):
        if n % d == 0:
            out.update((d, n // d))
    return sorted(out)


