def q_si(cfg):
    return cfg.qbar_ml_min / 6e7


def square_table(cfg):
    """One period of the trapezoid square wave [(t, Q)]: edges of width
    tau_v centred on the switching instants 0 and D*P (qs_model.Square)."""
    P, D = cfg.period, cfg.duty
    q_on, q_off = q_si(cfg) / D, 0.0
    tau = cfg.valve_edge()
    mid = 0.5 * (q_on + q_off)
    h = 0.5 * tau
    return [(0.0, mid), (h, q_on), (D * P - h, q_on), (D * P + h, q_off),
            (P - h, q_off), (P, mid)]


def waveform_q(cfg, t, ramp=True):
    """Python reference of the inlet volumetric flow [m3/s] (with the
    template's start-up ramp)."""
    t = np.asarray(t, float)
    Q = q_si(cfg)
    if cfg.waveform == "steady":
        q = np.full_like(t, Q)
    elif cfg.waveform == "sine":
        q = Q * (1.0 + cfg.amp * np.sin(2 * np.pi * cfg.freq_hz * t))
    elif cfg.edge == "ideal":
        ph = np.mod(t * cfg.freq_hz, 1.0)
        q = np.where(ph < cfg.duty, Q / cfg.duty, 0.0)
    else:
        tt, qq = np.array(square_table(cfg)).T
        q = np.interp(np.mod(t, cfg.period), tt, qq)
    if ramp:
        q = q * np.clip(t / cfg.ramp_s, 0.0, 1.0)
    return q


def flow_entry(cfg):
    Q = q_si(cfg)
    if cfg.waveform == "steady":
        inner = f"{{ type constant; value {_f17(Q)}; }}"
    elif cfg.waveform == "sine":
        inner = f"""{{
                    type        sine;
                    frequency   {_f17(cfg.freq_hz)};
                    amplitude   1;
                    scale       {_f17(cfg.amp * Q)};   // A * Qbar
                    level       {_f17(Q)};         // Qbar
                    t0          0;
                }}"""
    elif cfg.edge == "ideal":
        # edge sensitivity: the template's instantaneous square (v2606
        # Square.H: mark/space keys, verified 2026-09-01)
        a = Q / (2 * cfg.duty)
        inner = f"""{{
                    type        square;
                    frequency   {_f17(cfg.freq_hz)};
                    amplitude   {_f17(a)};
                    scale       1;
                    level       {_f17(a)};
                    t0          0;
                    mark        {_f17(cfg.duty)};
                    space       {_f17(1 - cfg.duty)};
                }}"""
    else:
        rows = " ".join(f"({_f17(t)} {_f17(q)})" for t, q in square_table(cfg))
        inner = f"""{{
                    // trapezoid square wave (D-T): ON {_f17(Q / cfg.duty)} m3/s for
                    // D = {cfg.duty:g} of P = {cfg.period:g} s, linear valve edges of
                    // tau_v = {cfg.valve_edge():g} s centred on the switching instants,
                    // repeated every period (TableBase outOfBounds repeat)
                    type        table;
                    values      ({rows});
                    outOfBounds repeat;
                    interpolationScheme linear;
                }}"""
    return f"""volumetricFlowRate
            {{
                type    scale;
                scale   {{ type linearRamp; start 0; duration {_f17(cfg.ramp_s)}; }}
                value   {inner}
            }}"""


