def poly_expr(c, var="T"):
    """Horner form of a polynomial for an OpenFOAM expression."""
    c = list(c)
    while len(c) > 1 and c[-1] == 0.0:
        c.pop()
    s = _f17(c[-1])
    for ci in reversed(c[:-1]):
        s = f"({_f17(ci)} + {var}*{s})"
    return s


