def _set_entry(txt, key, value, comment=""):
    import re
    new = f"{key:<16}{value};" + (f"   // {comment}" if comment else "")
    txt, n = re.subn(rf"^{key}\s+[^\n]*$", lambda _m: new, txt, flags=re.M)
    if n != 1:
        raise ConfigError(f"housing_physics: expected one '{key}' entry in "
                          f"the template controlDict, found {n}")
    return txt


def control_dict(template_text, cfg, lat):
    t = template_text
    if "writePrecision  17;" not in t:
        raise ConfigError("housing_physics: the template controlDict must "
                          "write at 17 digits (restart precision, K0-design "
                          "§10.4 item 4)")
    stage = {"full": "pre-circulation + discharge", "precirc":
             "pre-circulation only (heat-on state)", "heat":
             "discharge from the pre-circulated state"}[cfg.run_stage]
    t = _set_entry(t, "endTime", _f17(cfg.t_end),
                   f"RUN_STAGE {cfg.run_stage}: {stage}; heat on at t_pre = "
                   f"{cfg.t_pre:g} s (housing_physics)")
    t = _set_entry(t, "deltaT", _f17(cfg.dt), "fixed dt (D-T lattice)")
