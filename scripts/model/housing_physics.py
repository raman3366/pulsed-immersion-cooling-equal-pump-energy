#!/usr/bin/env python3
"""Housing physics and instrumentation for the K0 housing case family
(WP 2.5c; plan D-A, D-J, D-P, D-R, D-T, NEW-14, NEW-15, NEW-20).

This module renders the dictionaries that `cases/k0housing/makePhysics.py`
(generated by scripts/mesh/make_k0housing.py from cases/template, rule 2)
writes at Allrun.pre time, and it is the Python reference for what the
solver is asked to do (waveform, injected heat power, time lattice), so
post-processing and tests use the same numbers as the case.

Every behaviour is behind a switch read from the case environment
(case.env, written by scripts/generate_cases.py). Production defaults are
marked [P]; docs/model/housing-physics.md is the design note.

  FLUID_PROPS  tdep [P]        coolant rho, mu, k, c_p (T) polynomials from
                                data/reference/novec7200_properties.yaml
                                (heRhoThermo / polynomial / hPolynomial /
                                icoPolynomial: the only liquid combination
                                rhoReactionThermo offers, D-R)
               const            25 C anchors (properties.yaml) with a linear
                                rho(T) of expansion BETA (default: the fitted
                                beta at 25 C); the D-R "constant set"
               cp_zheng, mu_wt  tdep with the c_p (Zheng 2014 level) or mu
                                (Warrier & Teja level) sensitivity set
  HEAT_MODEL   H0 [P]           Liu Eq. 5 at 3C (heatgen.yaml); 1C/2C from
                                the digitised Fig 3b (heatgen_h0_fig3b.yaml)
               H1               Bernardi heat from Liu's 3C voltage
                                (heatgen_h1.yaml). REFUSED while that file
                                says usable_as_Hstar: false, unless
                                HEAT_DIAGNOSTIC=1 (case then never
                                claim-eligible)
               const            HEAT_W watts per cell (film / probe runs)
               none             no source (isothermal: impedance runs,
                                pre-circulation states)
  HEAT_SCALE   1 [P]            multiplies the model power (H0 / H1 / const):
                                the D-A.3 energy-scaled heat variant and the
                                NEW-6 heat-scale sensitivity (a robustness
                                run, never a confirmatory member)
  CRATE        3 [P] | 2 | 1    discharge rate; sets t_discharge
  H0_TIME      seconds [P]      Eq. 5 with t in s (D-A literal; option (a)
                                of docs/pending-decisions/WP2.7.md item 4)
               dod              every rate DOD-normalised (option (b))
  WAVEFORM     steady | sine | square;  QBAR_ML_MIN, FREQ_HZ, AMP, DUTY
  EDGE         dt [P]           square-wave valve edge tau_v = min(50 ms,
                                ON/5) (D-T), linear ramps centred on the
                                switching instants (as scripts/post/
                                qs_model.Square)
               ideal | <ms>     edge sensitivities (not claim-bearing)
  DT_MS        12.5 [P]         fixed time step from 25*2^-k ms (D-T); the
                                provisional dt* (PROJECT.md §2.5 NEW-2.1,
                                2026-09-28: GDT1 steady ladder) until G-dt
                                and FREEZE
  N_MIN        40 [P]           steps per period (NEW-2; Womersley sets it)
  N_PHI_MIN    8 [P]            phase samplers per period (16: mechanism
                                cases, NEW-20)
  DIAGNOSTIC   0 [P]            1 = ladder / coupling run: exempt from N_MIN
  PRECIRC_S    auto [P]         isothermal pre-circulation before heat-on
                                (NEW-14.1, 2026-09-28): 120 s steady; pulsed
                                the smallest whole number of periods >=
                                max(120 s, ramp + 5 periods); 0 = impulsive-
                                start sensitivity; ladder/coupling rungs set
                                30 s explicitly (GDT1 protocol)
  RUN_STAGE    full [P]         one solver run 0 -> t_pre + t_dis, heat on
                                at t_pre (no seed possible)
               precirc          0 -> t_pre only (a shared pre-circulated
                                state, or stage 1 of the two-stage run)
               heat             t_pre -> t_pre + t_dis from a pre-circulated
                                state (INIT_FROM or Allrun.heat)
  HEAT_STEPS   (unset) [P]      smoke override: the heated stage lasts this
                                many steps (never claim-eligible)
  SEED         0 [P]            noise-pilot member k > 0: smooth linear
                                +-TILT_K (0.05 K) tilt of the six cells in a
                                random direction at heat-on (D-L; tilt_setup
                                says why cells only); needs the two-stage
                                run (RUN_STAGE precirc + Allrun.heat, or
                                heat + INIT_FROM)
  INIT_FROM    (unset) [P]      RUN_STAGE heat: the shared pre-circulated
                                state to start from (scripts/model/
                                init_from.py; NEW-14/NEW-25)
  PRECIRC_CHECK strict [P]      Allrun.heat refuses a pre-circulation that
                                fails the NEW-14 stationarity rule
                                (scripts/post/precirc_check.py) and
                                housing_metrics gates it on every
                                claim-eligible run (NEW-14.2); report =
                                smokes and diagnostic protocols (closurecal),
                                never claim-eligible
  SCHEME       cand1 [P]        D-J energy-transport candidates, least
                                diffusive first (cand1 limitedLinear 1;
                                cand2 + cellLimited gradients; cand3
                                vanLeer; cand4 cand1 + laplacian limited
                                corrected 0.33); cand1 is provisional until
                                the Stage-A scheme gate
  SAMPLERS     1 [P]            phase-locked plane samplers (NEW-20)
  SAMPLER_PERIODS 10 [P]        sampled whole periods at the end of the run
  WRITE_S      30 [P]           nominal field-write interval [s]
  MEASURE_S    (unset) [P]      window after t_pre of an isothermal run
                                (HEAT_MODEL none; default 10 periods or
                                30 s steady): the D-P impedance runs
  GRID, PORT_MULT, NOUTER       read by Allrun.pre (mesh level, port length,
                                PIMPLE outer correctors); recorded here
  K0_ZLEVER    far [P]          mesh option read by makeMesh.py: module =
                                the module-interior z-lever (K0-design
                                §10.14), off by default and not claim-
                                eligible until its D-row is adopted;
                                recorded here
  OUTLET_P     prgh [P]         riser-top outlet pressure reference: p_rgh
                                fixedValue 0 (gauge, PROJECT.md §4.3; D-G as
                                built), so p = rho g.r varies across the face
                                with the local density
               p                D-G.1 diagnostic (PROJECT.md §2.5a,
                                2026-10-02): prghPressure with p = 0 (v2606
                                syntax of $FOAM_TUTORIALS/heatTransfer/
                                buoyantSimpleFoam/comfortHotRoom 0.orig/
                                p_rgh), p uniform on the face; its start-up
                                p_rgh value is the hydrostatic -rho0 g.r_out,
                                and scripts/hydrostatic_init.py initialises p
                                = rho0 g.(r - r_out) to match. Never claim-
                                eligible until a dated row adopts it
  DIV_U        scheme [P]       div(phi,U) as SCHEME sets it (cand1..4:
                                Gauss limitedLinear 1)
               linear           D-P.7 (4)(ii) / D-P.9 diagnostic: Gauss
                                linear on div(phi,U) only (the limited
                                scheme's convective numerical dissipation
                                removed); never claim-eligible
  PHI_FACE     0 [P]            1 = add the face-based viscous dissipation
                                monitor PhiFace_fluid (D-P.7 (4), D-P.9: a
                                coded function object compiled at run time
                                by the pinned gcc-13; phi_face_monitor). An
                                instrument only: it reads U and thermo:mu
                                and changes no field, so claim eligibility
                                is unchanged; the cell-centred Phi_fluid
                                stays the registered gate's instrument

The heat source is injected at EXACT model power (D-J (i)): volumeMode
absolute makes the Function1 value the region's total power, which the
solver divides by the MESHED region volume (cellSetOption::V_,
SemiImplicitSource VDash_ = V_ for vmAbsolute; v2606 src). The discharge
clock is shifted by the pre-circulation with an inputValueMapper
(t - t_pre), and the source is inactive before heat-on (cellSetOption
timeStart = t_pre + dt/2).
"""

